type SpeechListener = (data: { text: string; langCode: SupportedLanguage; isSpeaking: boolean }) => void;
const speechListeners: Set<SpeechListener> = new Set();

export function subscribeSpeech(listener: SpeechListener) {
  speechListeners.add(listener);
  return () => {
    speechListeners.delete(listener);
  };
}

function notifySpeechListeners(text: string, langCode: SupportedLanguage, isSpeaking: boolean) {
  speechListeners.forEach(listener => {
    try {
      listener({ text, langCode, isSpeaking });
    } catch {
      // ignore
    }
  });
}

let cachedVoices: SpeechSynthesisVoice[] = [];
if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
  try {
    cachedVoices = window.speechSynthesis.getVoices();
    window.speechSynthesis.onvoiceschanged = () => {
      cachedVoices = window.speechSynthesis.getVoices();
    };
  } catch {
    // ignore
  }
}

let activeAudio: HTMLAudioElement | null = null;
let activeSafetyTimeout: ReturnType<typeof setTimeout> | null = null;

export function stopSpeaking() {
  if (activeSafetyTimeout) {
    clearTimeout(activeSafetyTimeout);
    activeSafetyTimeout = null;
  }
  try {
    if (Speech && typeof Speech.stop === 'function') {
      Speech.stop();
    }
  } catch {}
  if (activeAudio) {
    try {
      activeAudio.pause();
      activeAudio.currentTime = 0;
      activeAudio.src = '';
    } catch {}
    activeAudio = null;
  }
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    try {
      window.speechSynthesis.cancel();
    } catch {}
  }
  notifySpeechListeners('', 'en-US', false);
}

/**
 * Universal High-Fidelity Speech Engine:
 * Uses expo-speech natively on iOS/Android, with fallback to Web Speech API when running on web.
 */
export function speakText(text: string, langCode: SupportedLanguage = 'en-US') {
  if (!text || !text.trim()) return;

  soundFx.playTap();
  stopSpeaking();
  notifySpeechListeners(text, langCode, true);

  const cleanText = text.trim();

  // 1. Try Native Expo Speech
  try {
    if (Speech && typeof Speech.speak === 'function') {
      Speech.speak(cleanText, {
        language: langCode,
        rate: 0.9,
        onDone: () => notifySpeechListeners(cleanText, langCode, false),
        onError: () => notifySpeechListeners(cleanText, langCode, false),
      });
      return;
    }
  } catch (err) {
    // Continue to browser fallback
  }

  // 2. Browser fallback
  fallbackBrowserSpeech(cleanText, langCode, () => {
    notifySpeechListeners(cleanText, langCode, false);
  });
}

function fallbackBrowserSpeech(
  text: string, 
  langCode: SupportedLanguage, 
  onDone: () => void
) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    onDone();
    return;
  }

  try {
    if (window.speechSynthesis.paused) {
      window.speechSynthesis.resume();
    }
    window.speechSynthesis.cancel();

    const utterance = new SpeechSynthesisUtterance(text);
    utterance.lang = langCode;
    utterance.rate = 0.86;
    utterance.pitch = 1.0;

    if (!cachedVoices || cachedVoices.length === 0) {
      cachedVoices = window.speechSynthesis.getVoices();
    }

    const voices = cachedVoices;
    const langPrefix = langCode.substring(0, 2);
    const langSuffix = langCode.split('-')[1] || 'IN';

    let matchingVoice = voices.find(v => 
      v.lang.replace('_', '-').toLowerCase() === langCode.toLowerCase()
    );

    if (!matchingVoice) {
      matchingVoice = voices.find(v => 
        v.lang.toLowerCase().startsWith(langPrefix.toLowerCase())
      );
    }

    if (!matchingVoice) {
      const langOption = SUPPORTED_LANGUAGES.find(l => l.code === langCode);
      const nameKey = langOption ? langOption.label.toLowerCase() : '';
      if (nameKey) {
        matchingVoice = voices.find(v => 
          v.name.toLowerCase().includes(nameKey)
        );
      }
    }

    if (!matchingVoice && langSuffix === 'IN') {
      matchingVoice = voices.find(v => 
        v.lang.includes('IN') || v.name.toLowerCase().includes('india') || v.lang.startsWith('hi')
      );
    }

    if (matchingVoice) {
      utterance.voice = matchingVoice;
    }

    utterance.onend = () => {
      onDone();
    };
    utterance.onerror = () => {
      onDone();
    };

    window.speechSynthesis.speak(utterance);
  } catch (err) {
    console.warn('Fallback Web Speech error:', err);
    onDone();
  }
}

/**
 * Dynamic Translation helper utilizing server-side Google Cloud Translation API / Gemini translation
 */
export async function translateWithGoogleApi(
  text: string,
  targetLang: SupportedLanguage | string,
  sourceLang: string = 'en'
): Promise<string> {
  if (!text || !text.trim()) return text;
  try {
    const response = await fetch('/api/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, targetLang, sourceLang }),
    });
    if (!response.ok) {
      throw new Error(`Translation API error: status ${response.status}`);
    }
    const data = await response.json();
    return data.translatedText || text;
  } catch (error) {
    console.warn('Client translation request error, falling back to original:', error);
    return text;
  }
}
